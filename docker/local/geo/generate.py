#!/usr/bin/env python3
"""Generate the geo schema from the preserved initial SQL (no production data)."""
import pathlib,re,json
ROOT=pathlib.Path(__file__).resolve().parents[3]
source=(ROOT/'webapp/sql/001-schema.sql').read_text()
source=re.sub(r'--[^\n]*','',source)
def split(s):
    out=[]; start=0; depth=0
    for i,c in enumerate(s):
        if c=='(': depth+=1
        elif c==')': depth-=1
        elif c==',' and depth==0: out.append(s[start:i].strip());start=i+1
    out.append(s[start:].strip());return out
T={}
for name,body in re.findall(r'CREATE TABLE (\w+) \((.*?)\)\s*(?:PARTITION BY RANGE \(created_at\))?;',source,re.S):
    fields={};pk=[];uniques=[];refs={};defaults={}
    for item in split(body):
        if item.startswith('PRIMARY KEY'): pk=re.findall(r'\w+',item)[2:];continue
        if item.startswith('UNIQUE'): uniques.append(re.findall(r'\w+',item)[1:]);continue
        col,definition=item.split(None,1)
        typ=re.match(r'\w+(?:\(\d+\))?',definition).group()
        fields[col]={'type':typ,'notnull':'NOT NULL' in definition or 'PRIMARY KEY' in definition}
        if 'PRIMARY KEY' in definition: pk=[col]
        m=re.search(r'REFERENCES (\w+)\((\w+)\)',definition)
        if m: refs[col]=(m[1],m[2])
        m=re.search(r'DEFAULT (.*)',definition)
        if m: defaults[col]=m[1]
    T[name]={'fields':fields,'pk':pk,'uniques':uniques,'refs':refs,'defaults':defaults,'partial':[]}
T['image_objects']['refs']['owner_user_id']=('users','id')
T['users']['uniques'].append(['username'])
for name,table,cols,condition in re.findall(r'CREATE UNIQUE INDEX (\w+) ON (\w+)\(([^)]+)\) WHERE ([^;]+);',source):
    T[table]['partial'].append((name,cols.split(','),condition))
owners={'image_objects':'owner_user_id','login_sessions':'user_id','friendships':'user_low_id','follows':'follower_id','block_relations':'blocker_id','posts':'author_id','friend_requests':'requester_id','realmojis':'reactor_id','comments':'author_id','notifications':'user_id','administrator_sessions':'administrator_id'}
for name,t in T.items():
    t['owner']=owners.get(name)
    cols=set(t['pk'])|set(t['refs'])
    for u in t['uniques']: cols.update(u)
    for _,u,predicate in t['partial']:
        cols.update(u); cols.update(c for c in t['fields'] if re.search(r'\b'+c+r'\b',predicate))
    t['registry']=[c for c in t['fields'] if c in cols]
# No application schema objects are replaced: this file only initializes a NEW database.
s=['-- Generated by generate.py; edit the generator, not this file.',"CREATE SCHEMA geo;",'REVOKE ALL ON SCHEMA geo FROM PUBLIC;',"SET default_tablespace='local_global';"]
for name,t in T.items():
    fields=[f"{c} {t['fields'][c]['type']}"+(' NOT NULL' if t['fields'][c]['notnull'] else '') for c in t['registry']]
    fields += ["geo_region text NOT NULL CHECK (geo_region IN ('asia','europe','america'))",'PRIMARY KEY ('+','.join(t['pk'])+')','UNIQUE ('+','.join(t['pk']+['geo_region'])+')']
    fields += ['UNIQUE ('+','.join(u)+')' for u in t['uniques']]
    s += [f"CREATE TABLE geo.registry_{name} (\n  "+',\n  '.join(fields)+') TABLESPACE local_global SPLIT INTO 1 TABLETS;']
    for idx,cols,condition in t['partial']:
        s += [f"CREATE UNIQUE INDEX registry_{idx} ON geo.registry_{name} ({','.join(cols)}) WHERE {condition};"]
for name,t in T.items():
    for col,(target,key) in t['refs'].items():
        s += [f'ALTER TABLE geo.registry_{name} ADD FOREIGN KEY ({col}) REFERENCES geo.registry_{target}({key}) ON DELETE RESTRICT;']
    if t['owner']:
        col=t['owner'];target,key=t['refs'][col]
        s += [f'ALTER TABLE geo.registry_{name} ADD FOREIGN KEY ({col},geo_region) REFERENCES geo.registry_{target}({key},geo_region) ON UPDATE CASCADE ON DELETE RESTRICT;']
s += ['RESET default_tablespace;']
for name,t in T.items():
    fields=[f"{c} {f['type']}"+(' NOT NULL' if f['notnull'] else '') for c,f in t['fields'].items()]
    fields += ["placement_region text NOT NULL CHECK (placement_region IN ('asia','europe','america'))",'PRIMARY KEY ('+','.join(['placement_region']+t['pk'])+')',f"FOREIGN KEY ({','.join(t['pk']+['placement_region'])}) REFERENCES geo.registry_{name} ({','.join(t['pk']+['geo_region'])}) ON UPDATE CASCADE ON DELETE CASCADE"]
    s += [f'CREATE TABLE geo.data_{name} (\n  '+',\n  '.join(fields)+') PARTITION BY LIST(placement_region);']
    for r in ['asia','europe','america']:
        s += [f"CREATE TABLE geo.data_{name}_{r} PARTITION OF geo.data_{name} FOR VALUES IN ('{r}') TABLESPACE local_{r} SPLIT INTO 1 TABLETS;"]
    for col in sorted(t['refs']):
        s += [f'CREATE INDEX data_{name}_{col}_idx ON geo.data_{name} ({col});']
    cols=','.join(t['fields'])
    s += [f'CREATE VIEW public.{name} AS SELECT {cols} FROM geo.data_{name};']
    for col,default in t['defaults'].items():
        s += [f'ALTER VIEW public.{name} ALTER COLUMN {col} SET DEFAULT {default};']
    if name in ('users','posting_windows'): route='r := NEW.region;'
    elif t['owner']:
        col=t['owner'];target,key=t['refs'][col]
        route=f'SELECT geo_region INTO STRICT r FROM geo.registry_{target} WHERE {key}=NEW.{col} FOR KEY SHARE;'
    else: route="r := 'asia'; -- regionless control-plane entity"
    regcols=t['registry']; colslist=list(t['fields'])
    where=' AND '.join(f'{c}=OLD.{c}' for c in t['pk'])
    newwhere=' AND '.join(f'{c}=NEW.{c}' for c in t['pk'])
    immutable=' OR '.join(f'NEW.{c} IS DISTINCT FROM OLD.{c}' for c in t['pk'])
    s += [f'''CREATE FUNCTION geo.write_{name}() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,geo AS $body$
DECLARE r text; current_row public.{name}%ROWTYPE;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    SELECT {cols} INTO current_row FROM geo.data_{name} WHERE {where} FOR UPDATE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    IF current_row IS DISTINCT FROM OLD THEN
      RAISE EXCEPTION 'concurrent modification of {name}; retry transaction' USING ERRCODE='40001';
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN
    DELETE FROM geo.registry_{name} WHERE {where};
    RETURN OLD;
  END IF;
  IF TG_OP='UPDATE' AND ({immutable}) THEN
    RAISE EXCEPTION 'immutable identity in {name}' USING ERRCODE='23514';
  END IF;
  {route}
  IF TG_OP='INSERT' THEN
    INSERT INTO geo.registry_{name} ({','.join(regcols)},geo_region)
      VALUES ({','.join('NEW.'+c for c in regcols)},r);
    INSERT INTO geo.data_{name} ({cols},placement_region)
      VALUES ({','.join('NEW.'+c for c in colslist)},r);
  ELSE
    UPDATE geo.registry_{name} SET {','.join(c+'=NEW.'+c for c in regcols)},geo_region=r WHERE {where};
    UPDATE geo.data_{name} SET {','.join(c+'=NEW.'+c for c in colslist)} WHERE {newwhere} AND placement_region=r;
  END IF;
  RETURN NEW;
EXCEPTION WHEN no_data_found THEN
  RAISE EXCEPTION 'referenced owner does not exist for {name}' USING ERRCODE='23503';
END
$body$;
CREATE TRIGGER write_{name} INSTEAD OF INSERT OR UPDATE OR DELETE ON public.{name} FOR EACH ROW EXECUTE FUNCTION geo.write_{name}();''']
s += ["""-- A partitioned CREATE INDEX does not inherit each child's tablespace in YSQL.
-- Move every secondary child index explicitly; primary indexes already match.
SELECT format('ALTER INDEX %s SET TABLESPACE %I',i.indexrelid::regclass,t.spcname)
FROM pg_index i JOIN pg_class c ON c.oid=i.indrelid
JOIN pg_namespace n ON n.oid=c.relnamespace
JOIN pg_tablespace t ON t.oid=c.reltablespace
WHERE n.nspname='geo' AND c.relkind='r' AND NOT i.indisprimary
  AND t.spcname IN ('local_asia','local_europe','local_america')
\\gexec"""]
s += ["REVOKE ALL ON ALL TABLES IN SCHEMA geo FROM PUBLIC;",'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA geo FROM PUBLIC;',"SELECT 'CREATE ROLE isureal_java_app LOGIN' WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='isureal_java_app')\\gexec",'REVOKE CREATE ON SCHEMA public FROM PUBLIC;','GRANT USAGE ON SCHEMA public TO isureal_java_app;']
for name in T: s += [f'GRANT SELECT,INSERT,UPDATE,DELETE ON public.{name} TO isureal_java_app;']
(ROOT/'docker/local/geo/schema.sql').write_text('\n\n'.join(s)+'\n')
(ROOT/'docker/local/geo/entities.json').write_text(json.dumps(T,indent=2)+'\n')
print(f'generated {len(T)} entities, {len(T)*3} regional partitions')
